# ---- 打乱并输出 ----
random.seed(417)
dist=[0,0,0,0]
lines=[]
for (tag,q,opts,a,why) in Q:
    correct = opts[a]
    order=[0,1,2,3]; random.shuffle(order)
    no=[opts[j] for j in order]
    na=no.index(correct)
    dist[na]+=1
    o = ", ".join("'" + x.replace("'", "\\'") + "'" for x in no)
    lines.append("  {tag:'%s',subj:'math',q:'%s',o:[%s],a:%d,why:'%s'}," % (
        tag, q.replace("'", "\\'"), o, na, why.replace("'", "\\'")))

io.open('_tmp_math3.js','w',encoding='utf-8').write("\n".join(lines))
